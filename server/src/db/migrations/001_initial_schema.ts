/**
 * Initial Postgres schema — a faithful translation of the SQLite schema that
 * `db/schema.ts` created with `CREATE TABLE IF NOT EXISTS`, plus the one thing
 * the PWA requires.
 *
 * Deliberate changes from the SQLite original, each with a reason:
 *
 * - Dates were TEXT; they are DATE here. Postgres parses 'YYYY-MM-DD' and will
 *   then refuse a malformed date instead of storing it.
 * - Money is NUMERIC, not a float. Binary floating point cannot represent 0.02
 *   exactly, and this app multiplies a per-litre price by a volume and adds GST.
 *   Temperatures and HDD stay DOUBLE PRECISION — they are measurements, not
 *   currency.
 * - `created_at` was TEXT DEFAULT CURRENT_TIMESTAMP; it is TIMESTAMPTZ DEFAULT
 *   now(). Fort Smith observes DST, so a timestamp without a zone is ambiguous
 *   twice a year.
 * - `fuel_fills.client_uuid` and `gauge_readings.client_uuid` are NEW. See below.
 *
 * Both offline-writable tables carry `client_uuid`: a gauge reading is taken at
 * the tank with no network exactly as a fill is, so it needs the same protection
 * against a retried flush. Weather, HVAC and settings do not — they are written
 * by the server or by import, never queued on a phone.
 *
 * `client_uuid` is NULLABLE, on purpose. Postgres permits many NULLs in a
 * UNIQUE column, so the historical fills imported from SQLite — which never had
 * a UUID — carry NULL, while every fill created by the PWA carries one. The
 * offline queue retries as its NORMAL path, not as an exception, so without this
 * constraint a retried flush would insert a duplicate fill. The project's stated
 * primary goal is the window-replacement ROI computed FROM the fill history, so
 * a duplicate fill corrupts the measurement the project exists to produce.
 */
